#!/usr/bin/env node
import fs from "node:fs";

const projectRoot = new URL("../", import.meta.url);

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(new URL(relativePath, projectRoot), "utf8"));
}

function sqlValue(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`Cannot encode non-finite number: ${value}`);
    return String(value);
  }
  return `'${String(value).replaceAll("'", "''")}'`;
}

function upsert({ table, conflictColumn, columns, rows }) {
  const values = rows
    .map((row) => `  (${columns.map((column) => sqlValue(row[column])).join(", ")})`)
    .join(",\n");
  const updates = columns
    .filter((column) => column !== conflictColumn)
    .map((column) => `  ${column} = excluded.${column}`)
    .concat("  updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now')")
    .join(",\n");

  return `INSERT INTO ${table} (${columns.join(", ")})\nVALUES\n${values}\nON CONFLICT(${conflictColumn}) DO UPDATE SET\n${updates};`;
}

const airports = readJson("data-source/atlas-airports-cn-hk-mo.json");
const airlines = readJson("data-source/atlas-airlines-cn-hk-mo.json");
const aircraftTypes = readJson("data-source/atlas-aircraft-types.json");

const statements = [
  "-- Generated by scripts/generate-flight-reference-sql.mjs. Do not edit by hand.",
  "-- Idempotent reference-data upserts; existing primary keys remain stable.",
  upsert({
    table: "atlas_airports",
    conflictColumn: "iata_code",
    columns: [
      "iata_code", "icao_code", "name", "name_zh", "city", "city_zh", "country",
      "country_code", "region", "latitude", "longitude", "timezone", "elevation_ft", "notes",
    ],
    rows: airports,
  }),
  upsert({
    table: "atlas_airlines",
    conflictColumn: "iata_code",
    columns: ["iata_code", "icao_code", "name", "name_zh", "country", "country_code", "callsign", "notes"],
    rows: airlines,
  }),
  upsert({
    table: "atlas_aircraft_types",
    conflictColumn: "icao_code",
    columns: ["icao_code", "manufacturer", "model", "model_zh", "notes"],
    rows: aircraftTypes,
  }),
];

const outputPath = new URL("flight-reference-data.sql", projectRoot);
fs.writeFileSync(outputPath, `${statements.join("\n\n")}\n`);
console.log(`Wrote ${outputPath.pathname}`);
console.log(`Rows: ${airports.length} airports, ${airlines.length} airlines, ${aircraftTypes.length} aircraft types`);
